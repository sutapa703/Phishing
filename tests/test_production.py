def test_no_application_filesystem_writes():
    data = (PROJECT_ROOT / 'examples' / 'prediction_sample.csv').read_bytes()
    with patch.object(Path, 'mkdir', side_effect=AssertionError('Runtime directory write')):
        response = app.test_client().post('/predict', data={'file': (BytesIO(data), 'sample.csv')})
    assert response.status_code == 200
    assert response.headers['Cache-Control'] == 'no-store'
    assert response.headers['X-Content-Type-Options'] == 'nosniff'


def test_concurrent_requests_do_not_share_output():
    frame = pd.read_csv(PROJECT_ROOT / 'examples' / 'prediction_sample.csv')
    def predict(count):
        content = frame.head(count).to_csv(index=False).encode()
        response = app.test_client().post('/predict', data={'file': (BytesIO(content), 'same.csv')})
        assert response.status_code == 200
        return len(pd.read_csv(BytesIO(response.data)))
    with ThreadPoolExecutor(max_workers=4) as pool:
        assert list(pool.map(predict, [1, 2, 3, 4])) == [1, 2, 3, 4]


def test_row_limit():
    frame = pd.read_csv(PROJECT_ROOT / 'examples' / 'prediction_sample.csv')
    large = pd.concat([frame.iloc[:1]] * 30001, ignore_index=True)
    response = app.test_client().post('/predict', data={'file': (BytesIO(large.to_csv(index=False).encode()), 'many.csv')})
    assert response.status_code == 400
    assert b'30,000 rows' in response.data


def test_portable_predictions_against_legacy_labels():
    frame = pd.read_csv(PROJECT_ROOT / 'prediction_artifacts' / 'phisingtest.csv')
    model = PortableModel(PROJECT_ROOT / 'models' / 'model.json')
    actual = model.predict(frame)
    # Expected classes generated by the unchanged original pickle on these exact rows.
    expected = np.load(PROJECT_ROOT / 'tests' / 'fixtures' / 'legacy_predictions.npy')
    np.testing.assert_array_equal(actual, expected)


